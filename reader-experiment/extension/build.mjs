// Builds the Send to Daylight extension (no npm dependencies):
//
//   dist/chrome/                      unpacked Chrome extension (Manifest V3, module service worker)
//   dist/safari/                      Safari Web Extension resources (Manifest V3, non-persistent background page)
//   dist/chrome-test/                 dist/chrome plus host access to 127.0.0.1 and localhost, for the end-to-end test
//   dist/send-to-daylight-chrome.zip  dist/chrome zipped (files at the root, as the Chrome Web Store expects)
//
//   node build.mjs [--target chrome|safari|chrome-test] [--no-zip]
//
// The protocol library is copied from ../share/js/daylight-share.js, the one source of truth, and so is the Lab module
// ../share/js/daylight-lab.js (LAB-PLAN 2.7.2). The Daylight server's client module ../server/client/daylight-server.js
// is copied with one change: its import of the protocol library points at the copy next to it. The version is
// package.json's, with the CI run number as the patch number when GITHUB_RUN_NUMBER is set (or RX_EXT_VERSION).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { zipDir } from './scripts/zip.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(here, 'src');
const DIST = path.join(here, 'dist');
const SHARE_LIB = path.join(here, '..', 'share', 'js', 'daylight-share.js');
const LAB_LIB = path.join(here, '..', 'share', 'js', 'daylight-lab.js');
const SERVER_LIB = path.join(here, '..', 'server', 'client', 'daylight-server.js');
const SERVER_IMPORT = "from '../../share/js/daylight-share.js';";
const TARGETS = ['chrome', 'safari', 'chrome-test'];

export function version() {
  if (process.env.RX_EXT_VERSION) return process.env.RX_EXT_VERSION;
  const base = JSON.parse(fs.readFileSync(path.join(here, 'package.json'), 'utf8')).version;
  const run = Number(process.env.GITHUB_RUN_NUMBER);
  if (Number.isInteger(run) && run > 0) return base.split('.').slice(0, 2).join('.') + '.' + (run % 65536);
  return base;
}

export function manifestFor(target, base = JSON.parse(fs.readFileSync(path.join(SRC, 'manifest.json'), 'utf8'))) {
  const m = structuredClone(base);
  m.version = version();
  if (target === 'chrome-test') {
    m.name += ' (test build)';
    m.host_permissions = [...m.host_permissions, 'http://127.0.0.1/*', 'http://localhost/*'];
  }
  if (target === 'safari') {
    delete m.minimum_chrome_version;
    // A non-persistent background page with one classic script works on every Safari with Manifest V3 (macOS and
    // iOS); module service workers came later and behave less predictably there.
    m.background = { scripts: ['background.js'], persistent: false };
    m.permissions = [...m.permissions, 'nativeMessaging'];
    // Safari draws toolbar icons as monochrome templates: give it the bare glyph.
    m.action.default_icon = 'icons/toolbar.svg';
    m.browser_specific_settings = { safari: { strict_min_version: '16.4' } };
  }
  return m;
}

/**
 * Bundles an ES module graph (relative imports only; `export function|class|const|let` declarations and
 * `import {a, b as c} from './x.js'` / `import * as x from './x.js'`) into one classic script.
 */
export function bundleClassic(entry) {
  const mods = new Map();
  const order = [];
  const importRe = /^import\s+(?:\*\s+as\s+([A-Za-z_$][\w$]*)|\{([^}]*)\})\s+from\s+'(\.{1,2}\/[^']+)';?[ \t]*$/gm;
  function visit(file) {
    if (mods.has(file)) {
      if (!mods.get(file).done) throw new Error(`import cycle through ${file}`);
      return mods.get(file).id;
    }
    const mod = { id: `__module${mods.size}`, file, exports: [], done: false };
    mods.set(file, mod);
    let body = fs.readFileSync(file, 'utf8').replace(importRe, (_, ns, names, spec) => {
      const dep = visit(path.resolve(path.dirname(file), spec));
      if (ns) return `const ${ns} = ${dep};`;
      const binds = names.split(',').map((s) => s.trim()).filter(Boolean).map((s) => {
        const [a, b] = s.split(/\s+as\s+/);
        return b ? `${a}: ${b}` : a;
      });
      return `const { ${binds.join(', ')} } = ${dep};`;
    });
    body = body.replace(/^export\s+(async\s+function\*?|function\*?|class|const|let)\s+([A-Za-z_$][\w$]*)/gm, (_, kw, name) => {
      mod.exports.push(name);
      return `${kw} ${name}`;
    });
    if (/^\s*export\b/m.test(body)) throw new Error(`${path.basename(file)}: unsupported export form for the classic bundle`);
    if (/^\s*import\b/m.test(body) || /\bimport\s*\(|import\.meta/.test(body)) throw new Error(`${path.basename(file)}: unsupported import for the classic bundle`);
    mod.body = body;
    mod.done = true;
    order.push(mod);
    return mod.id;
  }
  visit(path.resolve(entry));
  let out = '// Generated by build.mjs: the ES modules below bundled into one classic script for Safari.\n(() => {\n\'use strict\';\n';
  for (const m of order) {
    out += `\n// ---- ${path.basename(m.file)}\nconst ${m.id} = (() => {\n${m.body}\nreturn { ${m.exports.join(', ')} };\n})();\n`;
  }
  return out + '})();\n';
}

/**
 * The server client module as the extension (and the web sender) loads it: next to its copy of daylight-share.js.
 * Only the one import line changes; anything else in the module that needs rewriting is an error here, not at run time.
 */
export function serverModule(text = fs.readFileSync(SERVER_LIB, 'utf8')) {
  const n = text.split(SERVER_IMPORT).length - 1;
  if (n !== 1) throw new Error(`daylight-server.js: expected one import of ../../share/js/daylight-share.js, found ${n}`);
  const out = text.replace(SERVER_IMPORT, "from './daylight-share.js';");
  if (/from\s+'\.\.\//.test(out)) throw new Error('daylight-server.js: an import outside the module folder');
  return out;
}

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    const a = path.join(from, e.name), b = path.join(to, e.name);
    if (e.isDirectory()) copyDir(a, b);
    else if (e.isFile() && e.name !== '.DS_Store') fs.copyFileSync(a, b);
  }
}

export function buildTarget(target, distRoot = DIST) {
  if (!TARGETS.includes(target)) throw new Error(`unknown target ${target}`);
  const out = path.join(distRoot, target);
  fs.rmSync(out, { recursive: true, force: true });
  copyDir(SRC, out);
  fs.copyFileSync(SHARE_LIB, path.join(out, 'daylight-share.js'));
  fs.copyFileSync(LAB_LIB, path.join(out, 'daylight-lab.js'));
  fs.writeFileSync(path.join(out, 'daylight-server.js'), serverModule());
  const browser = target === 'safari' ? 'safari' : 'chrome';
  fs.writeFileSync(path.join(out, 'target.js'), `// Written by build.mjs.\nexport const TARGET = '${browser}';\n`);
  fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify(manifestFor(target), null, 2) + '\n');
  if (target === 'safari') {
    fs.writeFileSync(path.join(out, 'background.js'), bundleClassic(path.join(out, 'background.js')));
  }
  return out;
}

function main() {
  const args = process.argv.slice(2);
  const ti = args.indexOf('--target');
  const targets = ti >= 0 ? [args[ti + 1]] : TARGETS;
  fs.mkdirSync(DIST, { recursive: true });
  for (const t of targets) console.log(`built ${path.relative(process.cwd(), buildTarget(t)) || '.'} (version ${version()})`);
  if (targets.includes('chrome') && !args.includes('--no-zip')) {
    const zip = path.join(DIST, 'send-to-daylight-chrome.zip');
    const n = zipDir(path.join(DIST, 'chrome'), zip);
    console.log(`wrote ${path.relative(process.cwd(), zip)} (${n} files)`);
  }
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1] === fileURLToPath(import.meta.url)) main();
