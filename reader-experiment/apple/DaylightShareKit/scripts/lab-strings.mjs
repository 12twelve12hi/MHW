// Writes ../Sources/DaylightShareKit/LabStrings.swift from LAB_TEXT in share/js/daylight-lab.js, the one source of every
// Lab string (LAB-PLAN 6.3): every string under its dotted id, arrays joined with ",", exactly as
// share/vectors/lab-vectors.json › labText › strings lists them, and every array again as a real list (an item may hold
// a comma: four of the five serverSection.steps do, so a list is never read by splitting its joined form). Run it after
// the share lane changes LAB_TEXT:
//   node scripts/lab-strings.mjs           (writes the file)
//   node scripts/lab-strings.mjs --check   (exits 1 when the file is out of date; CI runs this)
// LabVectorTests checks the result against the vectors either way.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const lab = await import(pathToFileURL(join(here, '../../../share/js/daylight-lab.js')).href);
const out = join(here, '../Sources/DaylightShareKit/LabStrings.swift');

function flatten(o, prefix = '', acc = {}, lists = {}) {
  for (const [k, v] of Object.entries(o)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (typeof v === 'string') acc[key] = v;
    else if (Array.isArray(v)) {
      if (!v.every((x) => typeof x === 'string')) throw new Error(`LAB_TEXT.${key} holds something other than strings`);
      acc[key] = v.join(',');
      lists[key] = v;
    } else flatten(v, key, acc, lists);
  }
  return { strings: acc, lists };
}

/** A Swift string literal: backslash, quote and control characters escaped; everything else as it is. */
const swift = (s) => '"' + [...s].map((c) => {
  if (c === '\\') return '\\\\';
  if (c === '"') return '\\"';
  if (c === '\n') return '\\n';
  if (c === '\r') return '\\r';
  if (c === '\t') return '\\t';
  const u = c.codePointAt(0);
  if (u < 0x20 || u === 0x7f) return `\\u{${u.toString(16)}}`;
  return c;
}).join('') + '"';

const { strings, lists } = flatten(lab.LAB_TEXT);
const text = `// Generated by apple/DaylightShareKit/scripts/lab-strings.mjs from LAB_TEXT in share/js/daylight-lab.js. Do not edit:
// change LAB_TEXT (the share lane), then run node scripts/lab-strings.mjs. LabVectorTests pins every string to
// share/vectors/lab-vectors.json › labText › strings, and CI runs the script with --check.

/// Every Lab string by its dotted id (LAB_TEXT flattened; arrays joined with ","). Read them through \`LabText\`.
enum LabStrings {
    static let all: [String: String] = [
${Object.entries(strings).map(([k, v]) => `        ${swift(k)}: ${swift(v)},`).join('\n')}
    ]

    /// Every LAB_TEXT array as a list, by its dotted id. Read lists here: an item may hold a comma.
    static let lists: [String: [String]] = [
${Object.entries(lists).map(([k, v]) => `        ${swift(k)}: [\n${v.map((x) => `            ${swift(x)},`).join('\n')}\n        ],`).join('\n')}
    ]
}
`;
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (cur !== text) { console.error('LabStrings.swift is out of date: run node scripts/lab-strings.mjs'); process.exit(1); }
  console.log(`LabStrings.swift is current (${Object.keys(strings).length} strings, ${Object.keys(lists).length} lists)`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}: ${Object.keys(strings).length} strings, ${Object.keys(lists).length} lists`);
}
