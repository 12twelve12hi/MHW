// Writes ../src/main/kotlin/com/daylight/share/core/lab/LabStrings.kt from LAB_TEXT in share/js/daylight-lab.js (the
// one source of every Lab string, LAB-PLAN 6.3): every string under its dotted id, arrays joined with ",", exactly as
// share/vectors/lab-vectors.json › labText › strings lists them. Run it after the share lane changes LAB_TEXT:
//   node scripts/lab-strings.mjs           (writes the file)
//   node scripts/lab-strings.mjs --check   (exits 1 when the file is out of date)
// LabVectorsTest checks the result against the vectors either way.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const lab = await import(pathToFileURL(join(here, '../../../share/js/daylight-lab.js')).href);
const out = join(here, '../src/main/kotlin/com/daylight/share/core/lab/LabStrings.kt');

function flatten(o, prefix = '', acc = {}) {
  for (const [k, v] of Object.entries(o)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (typeof v === 'string') acc[key] = v;
    else if (Array.isArray(v)) acc[key] = v.join(',');
    else flatten(v, key, acc);
  }
  return acc;
}

const kt = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$').replace(/\n/g, '\\n') + '"';
const strings = flatten(lab.LAB_TEXT);
const text = `// Generated by share-core/scripts/lab-strings.mjs from LAB_TEXT in share/js/daylight-lab.js. Do not edit: change
// LAB_TEXT (the share lane), then run node scripts/lab-strings.mjs. LabVectorsTest pins every string to
// share/vectors/lab-vectors.json › labText › strings.
package com.daylight.share.core.lab

/** Every Lab string by its dotted id (LAB_TEXT flattened; arrays joined with ","). Read them through [LabText]. */
internal object LabStrings {
    val ALL: Map<String, String> = linkedMapOf(
${Object.entries(strings).map(([k, v]) => `        ${kt(k)} to ${kt(v)},`).join('\n')}
    )
}
`;
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (cur !== text) { console.error('LabStrings.kt is out of date: run node scripts/lab-strings.mjs'); process.exit(1); }
  console.log(`LabStrings.kt is current (${Object.keys(strings).length} strings)`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}: ${Object.keys(strings).length} strings`);
}
