// Assembles the web sender (static files, no bundling):
//
//   dist/site/                      the site to host (GitHub Pages serves it at …/send/)
//   dist/send-to-daylight-web.zip   the same files, to host anywhere
//
//   node build.mjs [--serve [port]]      (--serve also serves dist/site on http://127.0.0.1:<port>, default 8080)
//
// daylight-share.js and daylight-lab.js (../share/js), logic.js, lab-ui.js, lab-popup.js and lab-send.js
// (../extension/src) are copied in from their one source, and so is the Daylight server's client module
// (../server/client/daylight-server.js), with one change: its import of the protocol library points at the copy next to
// it (LAB-PLAN F00: the web sender's Lab). sw-sync.js (F07's Background Sync) and what it imports are bundled into one
// classic script, sw-lab.js, which sw.js loads with importScripts (the extension's bundleClassic, as for Safari's
// background). sw.js gets a hash of the site so browsers pick up each new version.
//
// The Lab release gate (LAB-PLAN 6.2) is not here: every web build has Lab, and rx-extension.yml holds the zip and the
// Pages deploy back while the code's Lab wave (scripts/lab-wave.mjs) waits in ../lab-release-gate.json.

import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { zipDir, listFiles } from '../extension/scripts/zip.mjs';
import { bundleClassic } from '../extension/build.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const DIST = path.join(here, 'dist');
const SITE = path.join(DIST, 'site');
const OWN = ['index.html', 'app.js', 'styles.css', 'web-logic.js', 'web-storage.js', 'web-lab.js', 'web-lab-page.js', 'web-flush.js', 'sw.js', 'manifest.webmanifest', 'icons'];
export const SHARED = {
  'daylight-share.js': path.join(here, '..', 'share', 'js', 'daylight-share.js'),
  'daylight-lab.js': path.join(here, '..', 'share', 'js', 'daylight-lab.js'),
  'logic.js': path.join(here, '..', 'extension', 'src', 'logic.js'),
  'lab-ui.js': path.join(here, '..', 'extension', 'src', 'lab-ui.js'),
  // Wave 1 (B1): the timeline's rows, the queue, Paste and send and the F02 entry point, as the popup draws them.
  'lab-popup.js': path.join(here, '..', 'extension', 'src', 'lab-popup.js'),
  'lab-send.js': path.join(here, '..', 'extension', 'src', 'lab-send.js'),
};
/** F07's Background Sync (LAB-PLAN F07, Web): sw-sync.js and its imports, bundled into the classic sw-lab.js. */
export const SW_ENTRY = 'sw-sync.js';
export const SW_BUNDLE = 'sw-lab.js';
const SERVER_LIB = path.join(here, '..', 'server', 'client', 'daylight-server.js');
const SERVER_IMPORT = "from '../../share/js/daylight-share.js';";

/**
 * The server client module as the page loads it: next to its copy of daylight-share.js. Only the one import line
 * changes; anything else in the module that would need rewriting is an error here, not at run time.
 */
export function serverModule(text = fs.readFileSync(SERVER_LIB, 'utf8')) {
  const n = text.split(SERVER_IMPORT).length - 1;
  if (n !== 1) throw new Error(`daylight-server.js: expected one import of ../../share/js/daylight-share.js, found ${n}`);
  const out = text.replace(SERVER_IMPORT, "from './daylight-share.js';");
  if (/from\s+'\.\.\//.test(out)) throw new Error('daylight-server.js: an import outside the module folder');
  return out;
}

export function buildSite(out = SITE) {
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(out, { recursive: true });
  for (const f of OWN) fs.cpSync(path.join(here, f), path.join(out, f), { recursive: true });
  for (const [name, src] of Object.entries(SHARED)) fs.copyFileSync(src, path.join(out, name));
  fs.writeFileSync(path.join(out, 'daylight-server.js'), serverModule());
  // The service worker's Background Sync: bundled from the site's own copies, so it runs exactly the page's code.
  fs.copyFileSync(path.join(here, SW_ENTRY), path.join(out, SW_ENTRY));
  fs.writeFileSync(path.join(out, SW_BUNDLE), bundleClassic(path.join(out, SW_ENTRY)).replace(
    '// Generated by build.mjs: the ES modules below bundled into one classic script for Safari.',
    '// Generated by web/build.mjs: sw-sync.js and its imports bundled into one classic script for sw.js (F07).'));
  fs.rmSync(path.join(out, SW_ENTRY));
  const hash = createHash('sha256');
  for (const rel of listFiles(out).filter((f) => f !== 'sw.js')) hash.update(rel).update(fs.readFileSync(path.join(out, rel)));
  const build = hash.digest('hex').slice(0, 12);
  const swPath = path.join(out, 'sw.js');
  fs.writeFileSync(swPath, fs.readFileSync(swPath, 'utf8').replace("'__BUILD__'", `'${build}'`));
  return { out, build };
}

const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.webmanifest': 'application/manifest+json', '.png': 'image/png', '.svg': 'image/svg+xml', '.json': 'application/json' };

/** A static server for dist/site (tests and local use). */
export function serve(root = SITE, port = 0, host = '127.0.0.1') {
  const server = http.createServer((req, res) => {
    const u = new URL(req.url, 'http://x');
    if (req.method !== 'GET' && req.method !== 'HEAD') { res.writeHead(405, { 'Content-Type': 'text/plain' }); return res.end('405 Not Allowed'); }
    let rel = decodeURIComponent(u.pathname).replace(/^\/+/, '');
    if (rel === '' || rel.endsWith('/')) rel += 'index.html';
    const file = path.resolve(root, rel);
    if (!file.startsWith(path.resolve(root)) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) { res.writeHead(404); return res.end('not found'); }
    res.writeHead(200, { 'Content-Type': TYPES[path.extname(file)] ?? 'application/octet-stream', 'Cache-Control': 'no-cache' });
    res.end(req.method === 'HEAD' ? undefined : fs.readFileSync(file));
  });
  return new Promise((resolve) => server.listen(port, host, () => resolve({
    server, url: `http://${host}:${server.address().port}`, close: () => new Promise((r) => { server.closeAllConnections?.(); server.close(() => r()); }),
  })));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { out, build } = buildSite();
  console.log(`built ${path.relative(process.cwd(), out) || '.'} (build ${build})`);
  const zip = path.join(DIST, 'send-to-daylight-web.zip');
  console.log(`wrote ${path.relative(process.cwd(), zip)} (${zipDir(out, zip)} files)`);
  const si = process.argv.indexOf('--serve');
  if (si > 0) {
    const s = await serve(SITE, Number(process.argv[si + 1]) || 8080);
    console.log(`serving ${s.url}/`);
  }
}
